@pytest.mark.asyncio
async def test_generate_structured_fallback_on_primary_schema_error():
    """
    Verify that if the primary model in a tier outputs malformed JSON or invalid schema,
    generate_structured automatically falls back to the next candidate model in the tier.
    """
    call_log = []
    gateway = LLMGateway(provider_invoker=None)
    route = gateway.get_models_for_tier("reasoning")

    async def mock_smart_fallback_invoker(model: str, prompt: str, **kwargs):
        call_log.append(model)
        if model == route[0]:
            # Primary model outputs unparseable prose
            return {
                "content": "Sorry, I am unable to format the review as JSON.",
                "input_tokens": 100,
                "output_tokens": 30,
                "provider": "test"
            }
        # Fallback model produces valid structured output
        return {
            "content": '```json\n{"approved": true, "score": 9.0, "comments": ["Fallback model saved the day"]}\n```',
            "input_tokens": 100,
            "output_tokens": 40,
            "provider": "test"
        }

    gateway.custom_invoker = mock_smart_fallback_invoker
    parsed_model, response = await gateway.generate_structured(
        prompt="Review security policy",
        response_model=CodeReviewOutput,
        tier="reasoning"
    )

    assert isinstance(parsed_model, CodeReviewOutput)
    assert parsed_model.approved is True
    assert parsed_model.score == 9.0
    assert route[0] in call_log
    assert route[1] in call_log
    assert response.model == route[1]
