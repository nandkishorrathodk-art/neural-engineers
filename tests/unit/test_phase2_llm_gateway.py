# 4. Token & Cost Tracking with Project & Employee Scopes
# =========================================================================

def test_cost_tracker_scopes_and_summary():
    """Verify CostTracker precision per project, employee, task, and aggregate summary."""
    tracker = CostTracker()

    # Call 1: Project Alpha, Emp 1, Task 1
    tracker.record_usage(
        model="gpt-4o",
        input_tokens=100_000,
        output_tokens=50_000,
        project_id="PROJ-ALPHA",
        employee_id="EMP-01",
        task_id="TASK-01"
    )

    # Call 2: Project Alpha, Emp 2, Task 2
    tracker.record_usage(
        model="claude-3-5-sonnet",
        input_tokens=200_000,
        output_tokens=100_000,
        project_id="PROJ-ALPHA",
        employee_id="EMP-02",
        task_id="TASK-02"
    )

    # Call 3: Project Beta, Emp 1, Task 3
    tracker.record_usage(
        model="gpt-4o-mini",
        input_tokens=500_000,
        output_tokens=200_000,
        project_id="PROJ-BETA",
        employee_id="EMP-01",
        task_id="TASK-03"
    )

    # Project Alpha aggregation
    alpha_cost = tracker.get_project_cost("PROJ-ALPHA")
    assert alpha_cost["call_count"] == 2
    assert alpha_cost["total_tokens"] == 450_000
    assert alpha_cost["cost_usd"] > 0

    # Project Beta aggregation
    beta_cost = tracker.get_project_cost("PROJ-BETA")
    assert beta_cost["call_count"] == 1
    assert beta_cost["total_tokens"] == 700_000

    # Employee 01 aggregation across projects
    emp1_cost = tracker.get_employee_cost("EMP-01")
    assert emp1_cost["call_count"] == 2
    assert emp1_cost["total_tokens"] == 850_000

    # Overall Summary
    summary = tracker.get_all_usage_summary()
    assert summary["total_calls"] == 3
    assert summary["total_tokens"] == 1_150_000
    assert summary["total_cost_usd"] > 0
    assert "gpt-4o" in summary["by_model"]
    assert "claude-3-5-sonnet" in summary["by_model"]
    assert "gpt-4o-mini" in summary["by_model"]


