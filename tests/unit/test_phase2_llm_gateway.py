@pytest.mark.asyncio
async def test_llm_gateway_transparent_fallback_cascade():
    """
    Simulates Primary model failing with 500 error, then First Fallback
    failing, and Second Fallback succeeding. Proves multi-tier resilience.
    """
    attempted = []
    gateway = LLMGateway(provider_invoker=None)
    route = gateway.get_models_for_tier("reasoning")
    assert len(route) >= 3

    async def mock_cascading_invoker(model: str, prompt: str, **kwargs):
        attempted.append(model)
        if model in route[:2]:
            raise ModelProviderError(f"Provider {model} unavailable")
        return {
            "content": f"Success from {model}",
            "input_tokens": 120,
            "output_tokens": 60,
            "provider": "test"
        }

    gateway.custom_invoker = mock_cascading_invoker
    response = await gateway.generate(
        prompt="Design high-throughput event processor",
        tier="reasoning"
    )

    assert response.model == route[2]
    assert f"Success from {route[2]}" in response.content
    assert response.metadata["attempted_models"] == route
    assert response.cost_usd > 0


@pytest.mark.asyncio
async def test_llm_gateway_rate_limit_detection_and_fallback():
    """
    Verifies that when primary model hits HTTP 429 / rate limit,
    the gateway recognizes RateLimitError and transparently falls back.
    """
    call_log = []
    gateway = LLMGateway(provider_invoker=None)
    route = gateway.get_models_for_tier("coding")

    async def mock_rate_limited_invoker(model: str, prompt: str, **kwargs):
        call_log.append(model)
        if model == route[0]:
            raise RateLimitError("429 Too Many Requests: Rate limit exceeded")
        return {
            "content": f"Code generated by {model}",
            "input_tokens": 100,
            "output_tokens": 50,
            "provider": "test"
        }

    gateway.custom_invoker = mock_rate_limited_invoker
    res = await gateway.generate(
        prompt="Implement quicksort in Python",
        tier="coding"
    )

    assert res.model == route[1]
    assert f"Code generated by {route[1]}" in res.content
    assert route[0] in call_log
    assert route[1] in call_log


