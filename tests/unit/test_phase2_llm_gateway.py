def test_extract_json_from_text_variants():
    """Test extracting JSON from raw string, markdown block, and embedded prose."""
    # Raw JSON
    raw = '{"approved": true, "score": 9.5, "comments": ["Great code"]}'
    res1 = extract_json_from_text(raw)
    assert res1["approved"] is True
    assert res1["score"] == 9.5

    # Markdown block ```json ... ```
    md = 'Here is the review:\n```json\n{"approved": false, "score": 4.0, "comments": ["Missing tests"]}\n```\nHope this helps.'
    res2 = extract_json_from_text(md)
    assert res2["approved"] is False
    assert res2["score"] == 4.0

    # Embedded in conversational prose without code fence
    prose = 'The result is {"approved": true, "score": 8.0, "comments": ["LGTM"]} as evaluated.'
    res3 = extract_json_from_text(prose)
    assert res3["approved"] is True


